CREATE TABLE IF NOT EXISTS organization (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    slug        VARCHAR(60)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_organization_slug UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS app_user (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  BIGINT       NOT NULL REFERENCES organization (id),
    email            VARCHAR(160) NOT NULL,
    password_hash    VARCHAR(100) NOT NULL,
    full_name        VARCHAR(120) NOT NULL,
    role             VARCHAR(20)  NOT NULL,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_user_org_email UNIQUE (organization_id, email),
    CONSTRAINT uk_user_id_org UNIQUE (id, organization_id),
    CONSTRAINT ck_user_role CHECK (role IN ('ORG_ADMIN', 'AGENT', 'CUSTOMER'))
);

CREATE TABLE IF NOT EXISTS ticket (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  BIGINT       NOT NULL REFERENCES organization (id),
    subject          VARCHAR(200) NOT NULL,
    description      TEXT         NOT NULL,
    priority         VARCHAR(10)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    requester_id     BIGINT       NOT NULL,
    assignee_id      BIGINT,
    closed_at        TIMESTAMPTZ,
    version          BIGINT       NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_ticket_requester_same_org FOREIGN KEY (requester_id, organization_id)
        REFERENCES app_user (id, organization_id),
    CONSTRAINT fk_ticket_assignee_same_org FOREIGN KEY (assignee_id, organization_id)
        REFERENCES app_user (id, organization_id),
    CONSTRAINT ck_ticket_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT ck_ticket_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED'))
);

CREATE INDEX IF NOT EXISTS idx_ticket_org_created   ON ticket (organization_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ticket_org_status    ON ticket (organization_id, status);
CREATE INDEX IF NOT EXISTS idx_ticket_org_priority  ON ticket (organization_id, priority);
CREATE INDEX IF NOT EXISTS idx_ticket_org_assignee  ON ticket (organization_id, assignee_id);
CREATE INDEX IF NOT EXISTS idx_ticket_org_requester ON ticket (organization_id, requester_id);

CREATE TABLE IF NOT EXISTS ticket_comment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   BIGINT      NOT NULL REFERENCES ticket (id),
    author_id   BIGINT      NOT NULL REFERENCES app_user (id),
    body        TEXT        NOT NULL,
    internal    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_comment_ticket ON ticket_comment (ticket_id, created_at);

CREATE TABLE IF NOT EXISTS ticket_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id      BIGINT       NOT NULL REFERENCES ticket (id),
    action         VARCHAR(30)  NOT NULL,
    from_value     VARCHAR(200),
    to_value       VARCHAR(200),
    changed_by_id  BIGINT       NOT NULL REFERENCES app_user (id),
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_history_action CHECK (action IN ('CREATED', 'STATUS_CHANGED', 'ASSIGNEE_CHANGED', 'PRIORITY_CHANGED'))
);

CREATE INDEX IF NOT EXISTS idx_history_ticket ON ticket_history (ticket_id, created_at);
